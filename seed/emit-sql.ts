// Emits supabase/seed.sql. One CTE statement per question (question + its 4
// choices, id captured via `returning`), verses batched 500 rows per statement.
import type { Ayah } from './corpus.ts';
import { normalizedText } from './corpus.ts';
import type { GenQuestion } from './questions.ts';

const VERSES_PER_STMT = 500;

function sqlStr(s: string): string {
  return `'${s.replace(/'/g, "''")}'`;
}

function sqlJson(o: unknown): string {
  return `${sqlStr(JSON.stringify(o))}::jsonb`;
}

export function emitSeedSql(verses: Ayah[], questions: GenQuestion[]): string {
  const out: string[] = [];
  out.push('-- generated by seed/generate-questions.mts — do not edit by hand.');
  out.push('-- regenerate: npm run gen:seed');
  out.push('begin;');

  for (let i = 0; i < verses.length; i += VERSES_PER_STMT) {
    const values = verses
      .slice(i, i + VERSES_PER_STMT)
      .map((a) =>
        `(${sqlStr(`${a.surah}:${a.ayah}`)}, ${a.surah}, ${a.ayah}, ${a.juz}, ${a.page}, ${sqlStr(a.uthmani)}, ${sqlStr(normalizedText(a.uthmani))})`,
      )
      .join(',\n  ');
    out.push(
      'insert into public.verses (ayah_key, surah, ayah, juz, page, text, text_normalized) values\n  ' +
        values +
        '\non conflict (ayah_key) do nothing;',
    );
  }

  for (const q of questions) {
    const opts = q.choices.map((c, idx) => `(${idx}, ${sqlStr(c)})`).join(', ');
    out.push(
      [
        'with q as (',
        '  insert into public.questions (type, quiz_key, prompt, instruction, ayah_key, payload, correct_idx, source)',
        `  values (${sqlStr(q.type)}, ${sqlStr(q.quizKey)}, ${sqlStr(q.prompt)}, ${sqlStr(q.instruction)}, ${sqlStr(q.ayahKey)}, ${sqlJson(q.payload)}, ${q.correctIdx}, 'generated')`,
        '  returning id',
        ')',
        'insert into public.choices (question_id, option_text, position)',
        `select q.id, c.option_text, c.position from q, (values ${opts}) as c(position, option_text);`,
      ].join('\n'),
    );
  }

  out.push('commit;');
  return out.join('\n') + '\n';
}
